"""Generates the Nova launcher icon (adaptive vector + legacy PNGs) from one shape list.

Run from the project root: python3 tool/make_icon.py [preview.png]
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw

BACKGROUND = "#0E1424"  # Outer Wilds deep space
PLANET = "#F28C28"  # campfire orange
MOON = "#E9E2D0"


def circle(cx, cy, r):
    """Circle from four cubic curves (k = 0.5523 is the standard arc fit)."""
    k = 0.5523 * r
    return [
        ("M", (cx, cy - r)),
        ("C", (cx + k, cy - r), (cx + r, cy - k), (cx + r, cy)),
        ("C", (cx + r, cy + k), (cx + k, cy + r), (cx, cy + r)),
        ("C", (cx - k, cy + r), (cx - r, cy + k), (cx - r, cy)),
        ("C", (cx - r, cy - k), (cx - k, cy - r), (cx, cy - r)),
    ]


# 108x108 adaptive-icon viewport; content stays inside the 66-unit safe circle.
# A small planet and its moon: simple enough to read at any size.
SHAPES = [
    (PLANET, circle(51, 57, 17)),
    (MOON, circle(72, 36, 5)),
]


def path_data(path):
    out = []
    for cmd, *pts in path:
        out.append(cmd + " ".join(f"{x:g},{y:g}" for x, y in pts))
    return " ".join(out) + " Z"


def polygon(path, scale, steps=24):
    pts, cur = [], None
    for cmd, *ctrl in path:
        if cmd in "ML":
            cur = ctrl[0]
            pts.append(cur)
            continue
        for i in range(1, steps + 1):
            t = i / steps
            if cmd == "Q":
                (x1, y1), (x2, y2) = ctrl
                x = (1 - t) ** 2 * cur[0] + 2 * (1 - t) * t * x1 + t * t * x2
                y = (1 - t) ** 2 * cur[1] + 2 * (1 - t) * t * y1 + t * t * y2
            else:
                (x1, y1), (x2, y2), (x3, y3) = ctrl
                x = ((1 - t) ** 3 * cur[0] + 3 * (1 - t) ** 2 * t * x1
                     + 3 * (1 - t) * t * t * x2 + t ** 3 * x3)
                y = ((1 - t) ** 3 * cur[1] + 3 * (1 - t) ** 2 * t * y1
                     + 3 * (1 - t) * t * t * y2 + t ** 3 * y3)
            pts.append((x, y))
        cur = ctrl[-1]
    return [(x * scale, y * scale) for x, y in pts]


def render(size, round_mask):
    """Legacy icon: 4x supersampled, background clipped to a circle or rounded square."""
    big = size * 4
    scale = big / 108
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)
    # Legacy icons show the full 108 viewport cropped to 72 like the adaptive mask would.
    inset = 18 * scale
    box = [0, 0, big - 1, big - 1]
    if round_mask:
        draw.ellipse(box, fill=BACKGROUND)
    else:
        draw.rounded_rectangle(box, radius=big * 0.22, fill=BACKGROUND)
    layer = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    ldraw = ImageDraw.Draw(layer)
    zoom = big / (108 - 2 * inset / scale) / scale  # map the 72-unit crop to full size
    for color, path in SHAPES:
        poly = [((x - inset) * zoom, (y - inset) * zoom) for x, y in polygon(path, scale)]
        ldraw.polygon(poly, fill=color)
    img.alpha_composite(layer)
    return img.resize((size, size), Image.LANCZOS)


def vector(color_override=None):
    paths = "\n".join(
        f'    <path android:fillColor="{color_override or color}"\n'
        f'        android:pathData="{path_data(path)}" />'
        for color, path in SHAPES
    )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tool/make_icon.py; edit the script, not this file. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
        f"{paths}\n</vector>\n"
    )


ADAPTIVE = """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""

DENSITIES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}


def main():
    if len(sys.argv) > 1:
        render(512, round_mask=False).save(sys.argv[1])
        return
    res = Path("android/app/src/main/res")
    for name, px in DENSITIES.items():
        render(px, round_mask=False).save(res / f"mipmap-{name}/ic_launcher.png")
        render(px, round_mask=True).save(res / f"mipmap-{name}/ic_launcher_round.png")
    (res / "drawable/ic_launcher_foreground.xml").write_text(vector())
    (res / "drawable/ic_launcher_monochrome.xml").write_text(vector("#FFFFFFFF"))
    anydpi = res / "mipmap-anydpi-v26"
    anydpi.mkdir(exist_ok=True)
    (anydpi / "ic_launcher.xml").write_text(ADAPTIVE)
    (anydpi / "ic_launcher_round.xml").write_text(ADAPTIVE)
    (res / "values/ic_launcher_colors.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
        f'    <color name="ic_launcher_background">{BACKGROUND}</color>\n</resources>\n'
    )


if __name__ == "__main__":
    main()
